"""
Sound effects for the edits: generated by ElevenLabs, royalty-free on a paid plan.

Owner, 2026-10-21 (in the HQ): ElevenLabs "all of that, plus sound effects".
A small bank in assets/sfx/, made by scripts/make_sfx.py from written
descriptions, with provenance in data/sfx.json. Two roles:
  impact  on the first frame, as the hook lands
  whoosh  leading into the quote
Like the edit music, only sounds the owner approved ("approved": true) air on
the channel; a DRY_RUN preview may use any of them so the owner can judge
them in a real video first. A REHEARSAL (REEL_REHEARSAL=1: Apelles' preview
of the next post, shown in the HQ before it airs) is not an audition: it
plays exactly what the live post will. On 2026-10-25 the first rehearsal
after the owner removed the slash still played it. render.py mixes them when
REEL_SFX=1.
"""
from __future__ import annotations

import json
import os
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANK = ROOT / "data" / "sfx.json"
ROLES = ("impact", "whoosh")
WHOOSH_LEAD = 0.35   # the whoosh peaks just as the quote arrives


def load() -> list[dict]:
    try:
        data = json.loads(BANK.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return []
    return [t for t in data if isinstance(t, dict) and t.get("id") and t.get("file") and t.get("role") in ROLES]


def _exists(t: dict) -> bool:
    p = ROOT / t["file"]
    return p.exists() and p.stat().st_size > 2000


def _on(name: str) -> bool:
    return os.environ.get(name, "0") not in ("0", "", "false", "False")


def _audition() -> bool:
    """A DRY_RUN preview that may try unapproved sounds: not a rehearsal."""
    return _on("DRY_RUN") and not _on("REEL_REHEARSAL")


def usable(audition: bool | None = None) -> list[dict]:
    """Approved sounds, or every sound in an audition preview. `audition`
    overrides the environment (False = what a live post would use)."""
    aud = _audition() if audition is None else audition
    return [t for t in load() if _exists(t) and (t.get("approved") is True or aud)]


def pick(role: str, seed: str, audition: bool | None = None) -> dict | None:
    aud = _audition() if audition is None else audition
    pool = sorted((t for t in usable(aud) if t["role"] == role), key=lambda t: t["id"])
    if not pool:
        return None
    forced = os.environ.get("REEL_SFX_" + role.upper(), "").strip()
    if forced and aud:
        hit = next((t for t in pool if t["id"] == forced), None)
        if hit:
            return hit
    return random.Random(f"{seed}|{role}").choice(pool)


def cues(quote_appear: float, seed: str) -> list[tuple[Path, float]]:
    """(sound file, start second) pairs for one video."""
    out = []
    impact = pick("impact", seed)
    if impact:
        out.append((ROOT / impact["file"], 0.0))
    whoosh = pick("whoosh", seed)
    if whoosh and quote_appear > 2 * WHOOSH_LEAD:
        out.append((ROOT / whoosh["file"], round(quote_appear - WHOOSH_LEAD, 2)))
    return out
